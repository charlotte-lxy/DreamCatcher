'use strict'
const { BrowserWindow, session } = require('electron')
const fs = require('fs')
const path = require('path')

const PARTITION = 'persist:auth:bilibili'
// 去掉 Electron 标识，避免 B 站把登录窗口当作异常客户端
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36'
const NAV = 'https://api.bilibili.com/x/web-interface/nav'
const HEADERS = {
  'User-Agent': UA,
  Referer: 'https://www.bilibili.com/',
  Origin: 'https://www.bilibili.com'
}

function getSession() {
  const s = session.fromPartition(PARTITION)
  s.setUserAgent(UA)
  return s
}

async function checkLogin() {
  const s = getSession()
  try {
    const res = await s.fetch(NAV, { headers: HEADERS, credentials: 'include' })
    const j = await res.json()
    const d = (j && j.data) || {}
    return { ok: !!d.isLogin, name: d.uname || '', face: d.face || '', vip: !!d.vipStatus }
  } catch (err) {
    return { ok: false, name: '', face: '', vip: false, error: String(err) }
  }
}

// 打开登录窗口，检测到登录成功或用户关闭窗口后返回
function openLogin(owner) {
  const s = getSession()
  return new Promise((resolve) => {
    const w = new BrowserWindow({
      width: 520,
      height: 720,
      parent: owner || undefined,
      title: '登录 B 站',
      autoHideMenuBar: true,
      webPreferences: { partition: PARTITION, contextIsolation: true, nodeIntegration: false, sandbox: true }
    })
    let settled = false
    const finish = async (reason) => {
      if (settled) return
      settled = true
      clearInterval(timer)
      const st = await checkLogin()
      if (!w.isDestroyed()) w.destroy()
      resolve(Object.assign({ reason }, st))
    }
    const timer = setInterval(async () => {
      const st = await checkLogin()
      if (st.ok) finish('logged-in')
    }, 2500)
    w.on('closed', () => finish('closed'))
    w.loadURL('https://passport.bilibili.com/login')
  })
}

// Netscape 格式序列化；HttpOnly 必须加 #HttpOnly_ 前缀，否则 yt-dlp 读不到 SESSDATA
function formatCookies(list) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Dreamcatcher', '']
  for (const c of list) {
    const includeSub = c.domain.startsWith('.') ? 'TRUE' : 'FALSE'
    const secure = c.secure ? 'TRUE' : 'FALSE'
    const expiry = Math.floor(c.expirationDate || 0)
    const prefix = c.httpOnly ? '#HttpOnly_' : ''
    lines.push([prefix + c.domain, includeSub, c.path || '/', secure, expiry, c.name, c.value].join('\t'))
  }
  return lines.join('\n') + '\n'
}

// 导出给 yt-dlp 用；必须全量，缺 buvid3 之类会被风控
async function exportCookies(dest) {
  const s = getSession()
  const all = await s.cookies.get({})
  const list = all.filter((c) => c.domain.includes('bilibili.com'))
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.writeFileSync(dest, formatCookies(list), { mode: 0o600 })
  return list.map((c) => c.name)
}

// B 站登录窗口固定直连：与下载出口保持一致，避免走境外代理触发风控
async function applyProxy() {
  await getSession().setProxy({ mode: 'direct' })
}

module.exports = { PARTITION, UA, getSession, checkLogin, openLogin, exportCookies, formatCookies, applyProxy }
